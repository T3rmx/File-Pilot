#!/usr/bin/env python3
"""Single-source version management for FilePilot.

``VERSION`` at the repository root is the source of truth. Every manifest that
ends up inside a package (backend, web, desktop, Tauri, PyInstaller) is kept in
sync from it, so a release can never ship mismatched version numbers.

Usage::

    python scripts/version.py show
    python scripts/version.py check
    python scripts/version.py set 1.2.0
    python scripts/version.py bump patch|minor|major

``check`` is run in CI. ``set``/``bump`` are what you run locally before
committing a new release line.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VERSION_FILE = ROOT / "VERSION"

SEMVER = re.compile(
    r"^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)"
    r"(?:-([0-9A-Za-z.-]+))?$"
)

# (path, kind). Kinds describe how many version fields a file contains.
TARGETS: list[tuple[str, str]] = [
    ("backend/pyproject.toml", "toml"),
    ("backend/app/__init__.py", "dunder"),
    ("web/package.json", "json1"),
    ("web/package-lock.json", "json2"),
    ("desktop/package.json", "json1"),
    ("desktop/package-lock.json", "json2"),
    ("desktop/src-tauri/tauri.conf.json", "json1"),
    ("desktop/src-tauri/Cargo.toml", "toml"),
]

TOML_VERSION = re.compile(r'(?m)^version\s*=\s*"[^"]+"')
DUNDER_VERSION = re.compile(r'__version__\s*=\s*"[^"]+"')
JSON_VERSION = re.compile(r'("version"\s*:\s*")[^"]+(")')
CARGO_LOCK_PACKAGE = re.compile(
    r'(?ms)(\[\[package\]\]\nname = "filepilot"\nversion = ")[^"]+(")'
)


def read_version() -> str:
    raw = VERSION_FILE.read_text(encoding="utf-8").strip()
    if not SEMVER.match(raw):
        raise SystemExit(f"VERSION must be semver (X.Y.Z), found {raw!r}")
    return raw


def _extract(path: Path, kind: str) -> list[str]:
    text = path.read_text(encoding="utf-8")
    if kind == "toml":
        match = TOML_VERSION.search(text)
        return [match.group(0).split('"')[1]] if match else []
    if kind == "dunder":
        match = DUNDER_VERSION.search(text)
        return [match.group(0).split('"')[1]] if match else []
    if kind == "json1":
        return [json.loads(text)["version"]]
    if kind == "json2":
        data = json.loads(text)
        return [data["version"], data["packages"][""]["version"]]
    raise SystemExit(f"unknown target kind {kind!r}")


def _write(path: Path, kind: str, version: str) -> None:
    text = path.read_text(encoding="utf-8")
    if kind == "toml":
        new_text, count = TOML_VERSION.subn(f'version = "{version}"', text, count=1)
    elif kind == "dunder":
        new_text, count = DUNDER_VERSION.subn(
            f'__version__ = "{version}"', text, count=1
        )
    elif kind == "json1":
        new_text, count = JSON_VERSION.subn(rf"\g<1>{version}\g<2>", text, count=1)
    elif kind == "json2":
        new_text, count = JSON_VERSION.subn(rf"\g<1>{version}\g<2>", text, count=2)
    else:
        raise SystemExit(f"unknown target kind {kind!r}")
    if count == 0:
        raise SystemExit(f"{path.relative_to(ROOT)}: no version field found")
    path.write_text(new_text, encoding="utf-8")


def set_version(version: str, *, quiet: bool = False) -> None:
    if not SEMVER.match(version):
        raise SystemExit(f"not a semver version: {version!r}")
    VERSION_FILE.write_text(f"{version}\n", encoding="utf-8")
    for relative, kind in TARGETS:
        path = ROOT / relative
        if not path.exists():
            raise SystemExit(f"missing manifest: {relative}")
        _write(path, kind, version)

    # Cargo.lock is generated by the first Tauri build and is not committed.
    cargo_lock = ROOT / "desktop/src-tauri/Cargo.lock"
    if cargo_lock.exists():
        text = cargo_lock.read_text(encoding="utf-8")
        new_text, count = CARGO_LOCK_PACKAGE.subn(
            rf"\g<1>{version}\g<2>", text, count=1
        )
        if count:
            cargo_lock.write_text(new_text, encoding="utf-8")

    if not quiet:
        print(f"version set to {version}")


def check() -> int:
    expected = read_version()
    failures: list[str] = []
    print(f"VERSION = {expected}")
    for relative, kind in TARGETS:
        path = ROOT / relative
        if not path.exists():
            failures.append(f"{relative}: missing")
            continue
        found = _extract(path, kind)
        if not found or any(value != expected for value in found):
            failures.append(f"{relative}: {', '.join(found) or 'no version field'}")
    if failures:
        print("\nversion manifests are out of sync:", file=sys.stderr)
        for failure in failures:
            print(f"  {failure}", file=sys.stderr)
        print(
            "\nrun: python scripts/version.py set " + expected,
            file=sys.stderr,
        )
        return 1
    print(f"{len(TARGETS)} manifests match")
    return 0


def bump(part: str) -> str:
    current = read_version().split("-", 1)[0]
    major, minor, patch = (int(piece) for piece in current.split("."))
    if part == "major":
        major, minor, patch = major + 1, 0, 0
    elif part == "minor":
        minor, patch = minor + 1, 0
    elif part == "patch":
        patch += 1
    else:
        raise SystemExit(f"unknown bump part {part!r}")
    version = f"{major}.{minor}.{patch}"
    set_version(version)
    return version


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    sub.add_parser("show", help="print the current version")
    sub.add_parser("check", help="verify every manifest matches VERSION")

    set_parser = sub.add_parser("set", help="set an exact version")
    set_parser.add_argument("version")

    bump_parser = sub.add_parser("bump", help="increment a version component")
    bump_parser.add_argument("part", choices=["major", "minor", "patch"])

    args = parser.parse_args()
    if args.command == "show":
        print(read_version())
        return 0
    if args.command == "check":
        return check()
    if args.command == "set":
        set_version(args.version)
        return check()
    if args.command == "bump":
        bump(args.part)
        return check()
    parser.error("unknown command")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
